using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.Metadata.Ecma335;
using System.Reflection.PortableExecutable;
using System.Security.Cryptography;
using System.Text;

namespace Neemle.DBAL.Tools;

/// <summary>Creates compiler-only visibility projections for exact typed private model accessors.</summary>
internal static class NativeModelBridge
{
    internal const string Marker = "// Neemle.ModelBridge.v1|";

    internal static void Generate(string referencesFile, string generatedFiles, string application, string output)
    {
        Directory.CreateDirectory(output);
        var generated = File.ReadAllLines(generatedFiles).Where(File.Exists).Select(Path.GetFullPath).Distinct().ToArray();
        var owners = new SortedSet<string>(StringComparer.Ordinal);
        var sources = new SortedSet<string>(StringComparer.Ordinal);
        var types = new HashSet<string>(StringComparer.Ordinal);
        foreach (var file in generated)
        {
            foreach (var line in File.ReadLines(file).Where(line => line.StartsWith(Marker, StringComparison.Ordinal)))
            {
                var parts = line.Substring(Marker.Length).Split('|');
                if (parts.Length != 3) throw new InvalidDataException("Invalid generated model bridge descriptor: " + file);
                foreach (var owner in Decode(parts[0])) owners.Add(owner);
                foreach (var type in Decode(parts[2])) types.Add(type);
                foreach (var source in Decode(parts[1]))
                {
                    var path = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(file)!, source));
                    if (!generated.Contains(path, StringComparer.Ordinal))
                        throw new InvalidDataException("The private model source is absent from the generated file manifest: " + path);
                    sources.Add(path);
                }
            }
        }

        var prerequisite = Path.Combine(output, "requires-input.txt");
        if (File.Exists(prerequisite)) File.Delete(prerequisite);
        if (owners.Count != 0 && !File.Exists(application))
        {
            Write(Path.Combine(output, "sources.txt"), "");
            Write(Path.Combine(output, "references.txt"), "");
            Write(prerequisite, application);
            return;
        }

        if (owners.Count == 0)
        {
            Write(Path.Combine(output, "sources.txt"), "");
            Write(Path.Combine(output, "references.txt"), "");
            return;
        }

        var appName = AssemblyName.GetAssemblyName(application).Name!;
        var inputs = File.ReadAllLines(referencesFile).Where(File.Exists).Append(application)
            .Select(Path.GetFullPath).Distinct(StringComparer.Ordinal).ToArray();
        var projected = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var resolved = new HashSet<string>(StringComparer.Ordinal);
        var audit = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var input in inputs)
        {
            var name = AssemblyName.GetAssemblyName(input).Name!;
            if (name == appName && input != Path.GetFullPath(application)) continue;
            var reference = input;
            if (owners.Contains(name))
            {
                reference = Path.Combine(output, "references", name + ".dll");
                Project(input, reference, types.Where(type => type.StartsWith(name + ":", StringComparison.Ordinal))
                    .Select(type => type.Substring(name.Length + 1)).ToHashSet(StringComparer.Ordinal));
                resolved.Add(name);
            }
            projected[name] = reference;
            audit[input] = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(input)));
        }
        var missing = owners.Except(resolved).ToArray();
        if (missing.Length != 0) throw new InvalidOperationException("Missing private model owner assemblies: " + string.Join(", ", missing));
        var attributes = new StringBuilder("// <auto-generated />\n#nullable enable\n");
        foreach (var owner in owners)
            attributes.Append("[assembly: global::System.Runtime.CompilerServices.IgnoresAccessChecksToAttribute(")
                .Append(System.Text.Json.JsonSerializer.Serialize(owner)).Append(")]\n");
        attributes.Append("namespace System.Runtime.CompilerServices {\n")
            .Append("[global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = true)]\n")
            .Append("internal sealed class IgnoresAccessChecksToAttribute : global::System.Attribute {\n")
            .Append("public IgnoresAccessChecksToAttribute(string assemblyName) { AssemblyName = assemblyName; }\n")
            .Append("public string AssemblyName { get; }\n} }\n");
        var extra = Path.Combine(output, "AccessChecks.g.cs");
        Write(extra, attributes.ToString());
        Write(Path.Combine(output, "sources.txt"), string.Join("\n", sources.Append(extra)) + "\n");
        Write(Path.Combine(output, "references.txt"), string.Join("\n", projected.Values) + "\n");
        Write(Path.Combine(output, "inputs.json"), System.Text.Json.JsonSerializer.Serialize(audit));
    }

    private static IEnumerable<string> Decode(string value)
        => Encoding.UTF8.GetString(Convert.FromBase64String(value)).Split('\n', StringSplitOptions.RemoveEmptyEntries);

    internal static void Project(string input, string output, IReadOnlySet<string> types)
    {
        var bytes = File.ReadAllBytes(input);
        using var stream = new MemoryStream(bytes, writable: false);
        using var pe = new PEReader(stream);
        var metadata = pe.GetMetadataReader();
        var start = pe.PEHeaders.MetadataStartOffset + metadata.GetTableMetadataOffset(TableIndex.TypeDef);
        var size = metadata.GetTableRowSize(TableIndex.TypeDef);
        foreach (var handle in metadata.TypeDefinitions)
        {
            var row = metadata.GetTypeDefinition(handle);
            if (!types.Contains(TypeName(handle))) continue;
            var flags = (uint)((row.Attributes & ~TypeAttributes.VisibilityMask)
                | (row.GetDeclaringType().IsNil ? TypeAttributes.Public : TypeAttributes.NestedPublic));
            BitConverter.GetBytes(flags).CopyTo(bytes, start + (MetadataTokens.GetRowNumber(handle) - 1) * size);
        }
        string TypeName(TypeDefinitionHandle handle)
        {
            var definition = metadata.GetTypeDefinition(handle);
            var name = metadata.GetString(definition.Name);
            if (!definition.GetDeclaringType().IsNil) return TypeName(definition.GetDeclaringType()) + "+" + name;
            var ns = metadata.GetString(definition.Namespace);
            return ns.Length == 0 ? name : ns + "." + name;
        }

        Directory.CreateDirectory(Path.GetDirectoryName(output)!);
        if (!File.Exists(output) || !File.ReadAllBytes(output).AsSpan().SequenceEqual(bytes)) File.WriteAllBytes(output, bytes);
    }

    private static void Write(string path, string text)
    {
        if (!File.Exists(path) || File.ReadAllText(path) != text) File.WriteAllText(path, text, new UTF8Encoding(false));
    }
}
