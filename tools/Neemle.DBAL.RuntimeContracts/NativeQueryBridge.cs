using System.Diagnostics;
using System.Security.Cryptography;
using System.Text.Json;

namespace Neemle.DBAL.Tools;

/// <summary>Compiles inferred iterator/implementation metadata with the caller's SDK compiler.</summary>
internal static class NativeQueryBridge
{
    internal static void Generate(string manifest, string application, string directory,
        string dotnet, string compiler, string resultFile, string? jsonGenerator = null, bool jsonOnly = false)
    {
        directory = Path.GetFullPath(directory);
        dotnet = Path.IsPathRooted(dotnet) ? dotnet : Environment.ProcessPath
            ?? throw new InvalidOperationException("The selected dotnet host could not be resolved.");
        Directory.CreateDirectory(directory);
        var source = Path.Combine(directory, "query-roots.g.cs");
        if (jsonOnly)
        {
            WriteIfChanged(source, "// <auto-generated />\n");
            WriteIfChanged(source + ".json", JsonSerializer.Serialize(new
            {
                bridgeAssembly = Generators.NativeMetadataNames.QueryAssembly(System.Reflection.AssemblyName.GetAssemblyName(application).Name!)
            }));
        }
        else NativeQueryIteratorMetadata.Generate(manifest, application, source);
        using var report = JsonDocument.Parse(File.ReadAllText(source + ".json"));
        var name = report.RootElement.GetProperty("bridgeAssembly").GetString()!;
        var assembly = Path.Combine(directory, name + ".dll");
        var references = File.ReadAllLines(manifest).Where(path => !string.IsNullOrWhiteSpace(path))
            .Append(application).Select(Path.GetFullPath).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
        var json = NativeJsonMetadata.Prepare(references, directory);
        var optionalReflection = jsonOnly ? [] : NativeOptionalReflectionMetadata.Prepare(references, directory);
        var sources = new[] { source }.Concat(json.Sources).Concat(optionalReflection).ToArray();
        if (json.Sources.Length != 0 && (jsonGenerator == null || !File.Exists(jsonGenerator)))
            throw new FileNotFoundException("The selected framework's System.Text.Json source generator is required for inferred JSON mappings.", jsonGenerator);
        if (references.Any(path => !File.Exists(path)) || !File.Exists(compiler) || !File.Exists(dotnet))
            throw new FileNotFoundException("The exact query bridge compiler inputs must exist.");
        var response = Path.Combine(directory, "compile.rsp");
        WriteIfChanged(response, string.Join(Environment.NewLine, new[]
        {
            "/nostdlib+", "/target:library", "/deterministic+", "/debug:embedded", "/nullable:enable", "/embed", "/warnaserror+",
            "/out:" + Quote(assembly)
        }.Concat(sources.SelectMany(path => new[] { "/embed:" + Quote(path), Quote(path) }))
            .Concat(json.References.Select(path => "/reference:" + Quote(path)))
            .Concat(json.Sources.Length == 0 ? [] : new[] { "/analyzer:" + Quote(jsonGenerator!) })) + Environment.NewLine);
        var compilerSha256 = Hash(compiler);
        var sourceSha256 = Hash(source);
        var jsonInputs = json.Sources.Concat(json.References.Except(references))
            .Concat(json.Sources.Length == 0 ? [] : new[] { jsonGenerator! }).ToDictionary(path => path, Hash, StringComparer.Ordinal);
        var referenceHashes = references.ToDictionary(path => path, Hash, StringComparer.Ordinal);
        var optionalReflectionInputs = optionalReflection.ToDictionary(path => path, Hash, StringComparer.Ordinal);
        var toolSha256 = Hash(typeof(NativeQueryBridge).Assembly.Location);
        var hostSha256 = Hash(dotnet);
        var hostCoreLibSha256 = Hash(typeof(object).Assembly.Location);
        var compilerDependencies = Directory.EnumerateFiles(Path.GetDirectoryName(Path.GetFullPath(compiler))!, "*", SearchOption.AllDirectories)
            .Where(path => Path.GetExtension(path) is ".dll" or ".json")
            .Order(StringComparer.Ordinal).ToDictionary(path => path, Hash, StringComparer.Ordinal);
        var responseSha256 = Hash(response);
        var cacheKey = Convert.ToHexString(SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(
            JsonSerializer.Serialize(new { schemaVersion = 1, compilerSha256, sourceSha256,
                toolSha256, hostSha256, hostCoreLibSha256, compilerDependencies, jsonInputs, optionalReflectionInputs,
                responseSha256, references = referenceHashes }))));
        var state = Path.Combine(directory, "compiler-inputs.json");
        if (File.Exists(state) && File.Exists(assembly))
        {
            try
            {
                using var previous = JsonDocument.Parse(File.ReadAllText(state));
                if (previous.RootElement.ValueKind == JsonValueKind.Object
                    && previous.RootElement.TryGetProperty("cacheKey", out var key) && key.ValueKind == JsonValueKind.String
                    && key.GetString() == cacheKey
                    && previous.RootElement.TryGetProperty("bridgeSha256", out var hash) && hash.ValueKind == JsonValueKind.String
                    && hash.GetString() == Hash(assembly))
                {
                    WriteIfChanged(resultFile, assembly + Environment.NewLine);
                    Console.WriteLine("DBAL query bridge inputs/output unchanged; compiler reused.");
                    return;
                }
            }
            catch (JsonException)
            {
                // An interrupted cache write must not prevent rebuilding from verified inputs.
            }
        }
        var start = new ProcessStartInfo(Path.GetFullPath(dotnet)) { UseShellExecute = false };
        start.ArgumentList.Add(Path.GetFullPath(compiler));
        start.ArgumentList.Add("/noconfig");
        start.ArgumentList.Add("@" + response);
        using var process = Process.Start(start) ?? throw new IOException("Could not start the selected SDK compiler.");
        process.WaitForExit();
        if (process.ExitCode != 0) throw new InvalidOperationException("Query bridge compilation failed: " + process.ExitCode);
        WriteIfChanged(resultFile, assembly + Environment.NewLine);
        WriteIfChanged(state, JsonSerializer.Serialize(new
        {
            cacheKey, compiler = Path.GetFullPath(compiler), compilerSha256,
            sourceSha256, toolSha256, hostSha256, hostCoreLibSha256, compilerDependencies, jsonInputs, optionalReflectionInputs,
            responseSha256, bridgeSha256 = Hash(assembly),
            references = referenceHashes
        }, new JsonSerializerOptions { WriteIndented = true }));

        static string Hash(string path) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path)));
        static void WriteIfChanged(string path, string text)
        {
            if (!File.Exists(path) || File.ReadAllText(path) != text) File.WriteAllText(path, text);
        }
        static string Quote(string path)
        {
            if (path.IndexOfAny(['\r', '\n']) >= 0) throw new ArgumentException("Newlines are not valid compiler input paths.");
            return "\"" + path.Replace("\"", "\\\"") + "\"";
        }
    }
}
