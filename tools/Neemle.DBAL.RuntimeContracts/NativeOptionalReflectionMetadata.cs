using System.Reflection;
using System.Text;
using System.Text.Json;

namespace Neemle.DBAL.Tools;

/// <summary>Infers optional member roots from provider contracts and actual selected SDK metadata.</summary>
internal static class NativeOptionalReflectionMetadata
{
    internal static string[] Prepare(string[] references, string directory)
    {
        using var context = new MetadataLoadContext(new SelectedCompilerAssemblyResolver(references), "System.Private.CoreLib");
        var assemblies = references.Select(context.LoadFromAssemblyPath).ToArray();
        var runtime = assemblies.SingleOrDefault(assembly => assembly.GetName().Name == "Neemle.DBAL.Runtime.Reflection");
        if (runtime == null) return [];
        var marker = runtime.GetType("Neemle.DBAL.Runtime.Reflection.NativeReflectionTypeRequestAttribute", true)!;
        var roots = new SortedDictionary<string, Type>(StringComparer.Ordinal);
        var requests = new List<object>();
        foreach (var assembly in assemblies)
        foreach (var attribute in assembly.GetCustomAttributesData().Where(attribute => attribute.AttributeType == marker))
        {
            var assemblyName = (string)attribute.ConstructorArguments[0].Value!;
            var typeName = (string)attribute.ConstructorArguments[1].Value!;
            var returnMethod = attribute.ConstructorArguments[2].Value as string;
            var owners = assemblies.Where(owner => owner.GetName().Name == assemblyName || owner.FullName == assemblyName).ToArray();
            if (owners.Length > 1) throw new InvalidOperationException("Ambiguous optional SDK assembly selection: " + assemblyName);
            var type = owners.SingleOrDefault()?.GetType(typeName, false, false);
            requests.Add(new { requester = assembly.FullName, assemblyName, typeName, returnMethod, selectedType = type?.AssemblyQualifiedName });
            if (type == null) continue;
            Add(type);
            if (returnMethod == null) continue;
            foreach (var method in type.GetMethods(BindingFlags.Public | BindingFlags.Static | BindingFlags.Instance)
                         .Where(method => method.Name == returnMethod && !method.ContainsGenericParameters))
            {
                var result = method.ReturnType;
                if (result == context.CoreAssembly!.GetType("System.Void")) continue;
                if (result == context.CoreAssembly.GetType("System.Object"))
                    throw new InvalidOperationException("An optional SDK return contract must expose its concrete result type: " + method);
                Add(result);
                if (!result.IsClass || result.IsSealed) continue;
                foreach (var candidate in assemblies.SelectMany(owner => owner.GetTypes()))
                    if (!candidate.ContainsGenericParameters && !candidate.IsAbstract && candidate.IsSubclassOf(result)) Add(candidate);
            }
        }

        var source = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace Neemle.DBAL.Inferred;\n")
            .Append("public static class OptionalReflectionRoots { public static void Register() {\n");
        foreach (var name in roots.Keys)
            source.Append("global::Neemle.DBAL.Runtime.Reflection.NativeReflectionTypes.Register(global::System.Type.GetType(")
                .Append(JsonSerializer.Serialize(name)).Append(", throwOnError: true)!);\n");
        source.Append("} }\n");
        var path = Path.Combine(directory, "optional-reflection-roots.g.cs");
        Write(path, source.ToString());
        Write(path + ".json", JsonSerializer.Serialize(new { requests, roots = roots.Keys, metadataOnly = true },
            new JsonSerializerOptions { WriteIndented = true }) + "\n");
        return [path];

        void Add(Type type)
        {
            if (type.ContainsGenericParameters || type.IsByRefLike || type.IsPointer || type.IsByRef || type.AssemblyQualifiedName == null)
                throw new InvalidOperationException("The optional SDK metadata contract is not a closed named CLR type: " + type);
            roots.TryAdd(type.AssemblyQualifiedName, type);
        }
        static void Write(string path, string text)
        {
            if (!File.Exists(path) || File.ReadAllText(path) != text) File.WriteAllText(path, text);
        }
    }
}
