using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace Neemle.DBAL.Tools;

/// <summary>Infers the framework's scalar JSON converter contracts without a duplicated type table.</summary>
internal static class NativeJsonScalarMetadata
{
    internal static void Generate(string manifest, string output)
    {
        var paths = File.ReadAllLines(manifest).Where(File.Exists).Select(Path.GetFullPath).Distinct(StringComparer.Ordinal).ToArray();
        using var context = new MetadataLoadContext(new SelectedCompilerAssemblyResolver(paths), "System.Private.CoreLib");
        var assembly = paths.Select(context.LoadFromAssemblyPath).Single(assembly => assembly.GetName().Name == "System.Text.Json");
        var services = assembly.GetType("System.Text.Json.Serialization.Metadata.JsonMetadataServices", true)!;
        var converter = assembly.GetType("System.Text.Json.Serialization.JsonConverter`1", true)!;
        var properties = services.GetProperties(BindingFlags.Public | BindingFlags.Static)
            .Where(property => property.GetMethod?.IsPublic == true && property.PropertyType.IsConstructedGenericType
                && property.PropertyType.GetGenericTypeDefinition() == converter)
            .OrderBy(property => property.Name, StringComparer.Ordinal).ToArray();
        if (properties.Length == 0) throw new InvalidDataException("The selected framework exposes no typed JSON scalar converters.");
        var source = new StringBuilder("// <auto-generated />\n#nullable enable\nnamespace Neemle.DBAL.Generated;\n")
            .Append("internal static class NativeJsonScalars {\n")
            .Append("private static readonly global::System.Text.Json.JsonSerializerOptions Options = new() { TypeInfoResolver = global::System.Text.Json.Serialization.Metadata.JsonTypeInfoResolver.Combine() };\n")
            .Append("internal static bool TryValue<T>(out global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T>? metadata) {\n");
        foreach (var property in properties)
        {
            var type = NativeJsonMetadata.CSharpName(property.PropertyType.GetGenericArguments()[0]);
            source.Append("if (typeof(T) == typeof(").Append(type).Append(")) { metadata = ")
                .Append("(global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T>)(object)")
                .Append("global::System.Text.Json.Serialization.Metadata.JsonMetadataServices.CreateValueInfo<").Append(type)
                .Append(">(Options, global::System.Text.Json.Serialization.Metadata.JsonMetadataServices.@")
                .Append(property.Name).Append("); return true; }\n");
        }
        source.Append("metadata = null; return false;\n}\n")
            .Append("internal static global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T> Value<T>() => ")
            .Append("TryValue<T>(out var metadata) ? metadata! : throw new global::System.NotSupportedException(\"No framework scalar JSON converter exists for '\" + typeof(T) + \"'.\");\n")
            .Append("internal static global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T[]> Array<T>() => ")
            .Append("TryValue<T[]>(out var metadata) ? metadata! : global::System.Text.Json.Serialization.Metadata.JsonMetadataServices.CreateArrayInfo<T>(Options, ")
            .Append("new global::System.Text.Json.Serialization.Metadata.JsonCollectionInfoValues<T[]> { ElementInfo = Value<T>() });\n")
            .Append("internal static global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<global::System.Collections.Generic.List<T>> List<T>() => ")
            .Append("global::System.Text.Json.Serialization.Metadata.JsonMetadataServices.CreateListInfo<global::System.Collections.Generic.List<T>, T>(Options, ")
            .Append("new global::System.Text.Json.Serialization.Metadata.JsonCollectionInfoValues<global::System.Collections.Generic.List<T>> { ElementInfo = Value<T>(), ObjectCreator = static () => new() });\n")
            .Append("internal static global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<global::System.ReadOnlyMemory<T>> Memory<T>() => ")
            .Append("TryValue<global::System.ReadOnlyMemory<T>>(out var metadata) ? metadata! : global::System.Text.Json.Serialization.Metadata.JsonMetadataServices.CreateReadOnlyMemoryInfo<T>(Options, ")
            .Append("new global::System.Text.Json.Serialization.Metadata.JsonCollectionInfoValues<global::System.ReadOnlyMemory<T>> { ElementInfo = Value<T>() });\n}\n");
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
        File.WriteAllText(output, source.ToString(), new UTF8Encoding(false));
        File.WriteAllText(output + ".json", JsonSerializer.Serialize(new
        {
            converterProperties = properties.Select(property => new { property.Name, type = property.PropertyType.GetGenericArguments()[0].AssemblyQualifiedName }),
            inputs = paths.ToDictionary(path => path, path => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path))))
        }, new JsonSerializerOptions { WriteIndented = true }));
    }
}
