using System.Reflection;
using System.Text.Json;

namespace Neemle.DBAL.Tools;

internal static class NativeAssemblyLoadErrorMetadata
{
    internal static void Generate(string resources, string output)
    {
        using var document = JsonDocument.Parse(File.ReadAllText(resources));
        var input = document.RootElement;
        if (Environment.Version.Major != 10) throw new InvalidOperationException("Select the supported .NET 10 JIT host for loader error inference.");
        var sentinel = "Neemle.DBAL.LoaderErrorProbe." + Guid.NewGuid().ToString("N");
        FileNotFoundException failure;
        try
        {
            Assembly.Load(sentinel);
            throw new InvalidOperationException("The missing-assembly probe unexpectedly resolved.");
        }
        catch (FileNotFoundException error) { failure = error; }
        var canonical = new AssemblyName(sentinel) { CultureName = string.Empty };
        canonical.SetPublicKeyToken([]);
        if (failure.FileName != canonical.FullName)
            throw new InvalidOperationException("The selected JIT host has an unsupported missing-assembly identity format.");
        var expected = string.Format(input.GetProperty("fileNotFoundLoadFile").GetString()!, failure.FileName);
        if (!failure.Message.StartsWith(expected, StringComparison.Ordinal)
            || failure.Message[expected.Length..].Any(character => !char.IsWhiteSpace(character)))
            throw new InvalidOperationException("The JIT loader error differs from the selected original runtime resource.");
        var template = failure.Message.Replace(failure.FileName!, "{0}", StringComparison.Ordinal);
        var text = "// <auto-generated /> Derived from dotnet/runtime " + input.GetProperty("commit").GetString() + ".\n"
            + "// Licensed to the .NET Foundation under the MIT license.\n"
            + "// SHA256 " + input.GetProperty("resourceSha256").GetString() + " " + input.GetProperty("resourcePath").GetString() + "\n"
            + "namespace Neemle.DBAL.Runtime.Reflection;\ninternal static class LoaderErrorFormats {\n"
            + "internal const string MissingAssembly = " + JsonSerializer.Serialize(template) + ";\n}\n";
        File.WriteAllText(output, text);
        File.WriteAllText(output + ".json", JsonSerializer.Serialize(new
        {
            resource = input.Clone(), actualRuntime = Environment.Version.ToString(),
            originalResourceMatchesJitMessage = true, suffix = failure.Message[expected.Length..],
            hostCoreLib = typeof(object).Assembly.Location,
            hostCoreLibSha256 = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(typeof(object).Assembly.Location))),
            generatorSha256 = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(typeof(NativeAssemblyLoadErrorMetadata).Assembly.Location))),
            canonicalIdentityVerified = true, hresult = failure.HResult, nativeVerified = false
        }, new JsonSerializerOptions { WriteIndented = true }) + "\n");
    }
}
